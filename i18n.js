var LANG_FONTS = {
  zh: "'Noto Sans SC', sans-serif",
  en: "'Noto Sans SC', sans-serif",
  ja: "'Noto Sans JP', 'Noto Sans SC', sans-serif"
};

/* ===== TRANSLATION HELPER ===== */
var _currentLang = 'zh';
var _langCallbacks = [];
window.t = function(key) { return (I18N[_currentLang] || I18N['zh'])[key] || key; };
window.getLang = function() { return _currentLang; };
window.onLangChange = function(fn) { _langCallbacks.push(fn); };

/* ===== APPLY TRANSLATIONS ===== */
function applyLang(lang) {
  var dict = I18N[lang];
  if (!dict) return;
  _currentLang = lang;

  /* text nodes */
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  /* innerHTML nodes (for keys with <br> / <span> etc.) */
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  /* placeholders */
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });

  /* option text */
  document.querySelectorAll('[data-i18n-opt]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-opt');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  /* update html lang attribute */
  var langMap = { zh: 'zh-CN', en: 'en', ja: 'ja' };
  document.documentElement.lang = langMap[lang] || lang;

  /* update active button */
  document.querySelectorAll('.lang-btn').forEach(function(btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  /* store preference */
  localStorage.setItem('sm_lang', lang);

  /* notify registered callbacks (e.g. shop re-render) */
  _langCallbacks.forEach(function(fn) { fn(lang); });
}

/* ===== INIT ===== */
(function() {
  var saved = localStorage.getItem('sm_lang') || 'zh';
  /* Run after DOM ready */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() { applyLang(saved); });
  } else {
    applyLang(saved);
  }

  /* Bind switcher buttons */
  document.addEventListener('click', function(e) {
    var btn = e.target.closest('.lang-btn');
    if (btn) applyLang(btn.getAttribute('data-lang'));
  });
})();
